/// 슬롯에 부품을 꽂기 전에 거쳐야 하는 수리 미니게임의 종류.
///
/// 슬롯이 어느 미니게임을 띄울지 인스펙터에서 고르게 하려고 만들었다.
/// bool 하나로는 미니게임이 둘 이상일 때 구분할 수 없다.
public enum RepairKind
{
    /// 미니게임 없이 즉시 설치 (기존 동작)
    None = 0,

    /// 변압기 모듈 수리: 볼트 풀기 3회 -> 모듈 안착(밸런스) -> 색선 4개 연결
    TransformerModule = 1,

    /// 배전반 퓨즈 수리: 차단기 내리기 -> 잔류전하 방전(R/S/T) -> 각도 맞춰 삽입 -> 차단기 올리기
    SwitchboardFuse = 2,
}
